"""Generate src/gc550-bootstrap-data.c from a recorded GC550 bootstrap.

The input is the lgx2userspace token format, one token per line or space
separated: '>HEX' is a command sent on bulk OUT 0x01, '<N' is an N-byte reply
read on bulk IN 0x81 straight after it.

The output is a flat, length-prefixed byte stream written with small macros so
every transaction is one readable, commented line, in the recorded order.
Reply lengths are not stored: the driver derives them from the command
(gc550_reply_len()), and this script refuses a recording where that rule does
not match what was recorded.

Run once and commit the output; building the driver never runs this script.

Usage: gen-bootstrap.py tools/recordings/gc550-f150158.txt > src/gc550-bootstrap-data.c
"""
import sys

CHIPS = {
    0x10: "FPGA", 0x18: "AIC3x", 0x20: "ADV7604 IO", 0x22: "ADV7604 CP",
    0x26: "ADV7604 AFE", 0x32: "ADV7604 REP", 0x34: "ADV7604 HDMI",
    0x36: "ADV7604 EDID", 0x38: "ADV7604 ESDP", 0x3D: "ADV7511",
    0x3F: "dev 0x3F", 0x46: "ADV7604 InfoFrame", 0x4A: "mixer",
    0x65: "dev 0x65", 0x74: "PCA9539A",
}

# Index of the first transaction of the Windows driver's steady-state loop
# (status reads plus interrupt clears / passthrough service writes). Only used
# for a section comment; everything is still replayed.
LOOP_START = 1766


def reply_len(cmd):
    if len(cmd) == 5 and cmd[0] == 0x02:
        return cmd[3]
    if len(cmd) == 6 and cmd[0] == 0x0E:
        return (cmd[4] << 8) | cmd[5]
    return 0


def parse(text):
    tokens = text.split()
    txns = []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if not tok.startswith(">") or len(tok) < 3 or len(tok) % 2 == 0:
            sys.exit(f"token {i}: expected a command, got {tok!r}")
        cmd = bytes.fromhex(tok[1:])
        rlen = 0
        if i + 1 < len(tokens) and tokens[i + 1].startswith("<"):
            rlen = int(tokens[i + 1][1:])
            i += 1
        if rlen != reply_len(cmd):
            sys.exit(f"transaction {len(txns)} ({cmd.hex()}): recorded reply {rlen} B, "
                     f"rule says {reply_len(cmd)} B")
        if len(cmd) > 255:
            sys.exit(f"transaction {len(txns)}: command longer than 255 bytes")
        txns.append(cmd)
        i += 1
    return txns


def h(b):
    return f"0x{b:02X}"


def describe(cmd):
    op = cmd[0]
    if op == 0x01 and len(cmd) >= 5 and cmd[2] == 0x01:
        addr, reg, data = cmd[1], cmd[3], cmd[4:]
        more = f" +{len(data)}" if len(data) > 1 else ""
        return f"W {CHIPS.get(addr, h(addr))} {reg:02X}{more}"
    if op == 0x02 and len(cmd) == 5 and cmd[2] == 0x01:
        return f"R {CHIPS.get(cmd[1], h(cmd[1]))} {cmd[4]:02X} n={cmd[3]}"
    note = {0x0E: "board-info read (512 B reply)", 0x08: "bridge command 08 (Windows sends it)"}
    return note.get(op, "bridge command")


def record(n, cmd):
    """One record: '/* index what */' then the length byte and command bytes,
    wrapped to stay within 100 columns."""
    out = [f"\t/* {n:4d} {describe(cmd)} */"]
    items = [h(len(cmd))] + [h(b) for b in cmd]
    lines, cur = [], "\t"
    for it in items:
        piece = it + ","
        if len(cur.expandtabs(8)) + len(piece) + 1 > 100:
            lines.append(cur.rstrip())
            cur = "\t"
        cur += piece + " "
    lines.append(cur.rstrip())
    return "\n".join(out + lines) + "\n"


def main():
    txns = parse(open(sys.argv[1]).read())
    out = sys.stdout
    out.write("// SPDX-License-Identifier: GPL-2.0-only OR MIT\n")
    out.write("/*\n * GENERATED by tools/gen-bootstrap.py - do not edit.\n *\n")
    out.write(" * The GC550 bootstrap as sent by the official Windows driver, recorded by\n")
    out.write(" * the lgx2userspace project (MIT, Copyright 2021 Chris Sawczuk and\n")
    out.write(" * contributors) with the AT88SC CryptoMemory login removed (upstream\n")
    out.write(" * commit f150158). Every entry is checked by gc550_guard_check() before\n")
    out.write(" * the first one is sent.\n */\n")
    out.write('#include "gc550-bootstrap.h"\n\n')
    out.write("/*\n * Each record is <len> <command bytes...>:\n")
    out.write(" *   W: 01 <addr> 01 <reg> <data...>   I2C write, no reply\n")
    out.write(" *   R: 02 <addr> 01 <count> <reg>     I2C read, <count> reply bytes\n */\n")
    out.write("const u8 gc550_bootstrap[] = {\n")
    size = 0
    for n, cmd in enumerate(txns):
        if n == LOOP_START:
            out.write("\n\t/*\n\t * From here on the recording is the Windows driver's steady-state\n"
                      "\t * loop: status reads, interrupt clears (ADV7604 IO *_CLR,\n"
                      "\t * ADV7511 0x96) and HDMI-out service writes. Replayed as recorded.\n\t */\n")
        out.write(record(n, cmd))
        size += 1 + len(cmd)
    out.write("};\n\n")
    out.write("const size_t gc550_bootstrap_size = sizeof(gc550_bootstrap);\n")
    out.write(f"const unsigned int gc550_bootstrap_count = {len(txns)};\n")
    out.write(f"\n/* {len(txns)} transactions, {size} bytes */\n")


if __name__ == "__main__":
    main()
